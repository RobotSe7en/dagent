def _history(text="old evidence " * 2000):
    return dagent.ConversationState(items=(
        dagent.UserMessage(run_id="run", content="Preserve this requirement."),
        dagent.AssistantMessage(run_id="run", content=text),
        dagent.AssistantMessage(run_id="run", content="latest step"),
    ))


class _Compactor:
    def __init__(self, *, fail=False):
        self.calls = []
        self.fail = fail
        self.source_request = None

    async def compact(self, previous, items, max_tokens, *, allow_fallback=False):
        self.calls.append(items)
        if self.fail:
            raise CompactionError("model offline")
        return dagent.ContextSummary(content="Earlier checks completed; keep the requirement.",
            source_item_count=(previous.source_item_count if previous else 0) + len(items))


def test_default_context_records_keep_released_shapes():
    policy = dagent.ContextPolicy().model_dump()
    assert not {"compaction_strategy", "allow_reference_fallback", "compaction_timeout_seconds"} & policy.keys()
    conversation = _history()
    assert "compaction_state" not in conversation.model_dump()
    assert "model_display" not in dagent.ToolResultMessage(call_id="c", name="q", status="completed").model_dump()
    assert "compaction_record" not in dagent.ContextSummary(content="old", source_item_count=1).model_dump()
    assert dagent.ContextPolicy.model_validate(policy).model_dump() == policy


