@pytest.mark.asyncio
async def test_server_shrink_discovered_by_summary_keeps_original_tools_and_paid_record(tmp_path):
    @dagent.tool
    def query(index: int) -> str:
        """Return verified evidence."""
        return f"verified evidence {index}"

    steps = 0

    def respond(request):
        nonlocal steps
        body = json.loads(request.content)
        raw = "\n".join(message.get("content", "") for message in body["messages"])
        match = re.search(r"Eligible source IDs: (\[[^\n]+\])", raw)
        if match:
            ids = json.loads(match.group(1))
            summary = json.dumps({"completed_work": [{"text": "Evidence received.", "source_ids": [ids[-1]]}]})
            return _completion("chat_completions", True, usage=_usage("chat_completions"), content=summary)
        steps += 1
        return _completion("chat_completions", False, usage=_usage("chat_completions"), content="",
            calls=(ToolCall(id=f"call_{steps}", name="tool_query", arguments={"index": steps}),))

    async with _endpoint(protocol="chat_completions", token_counting="heuristic",
                         context_window_tokens=131072, max_output_tokens=8192, responder=respond) as (provider, posts):
        async def count(call):
            from dagent.providers.model_io import ModelToolResultInput
            if call.request.purpose == "compaction":
                return ModelTokenCount(count=100, max_model_len=4096, exact=True, source="render")
            results = sum(isinstance(item, ModelToolResultInput) for item in call.request.items)
            return ModelTokenCount(count=110000 if results >= 2 else 100, max_model_len=131072,
                                   exact=True, source="render")

        provider.count_prepared = count
        with closing(dagent.Runner(provider=provider, workspace=tmp_path, skill_roots=[])) as runner:
            with pytest.raises(ProviderCapabilityError) as caught:
                await runner.run(dagent.ToolAgent(profile="conversation", capabilities=[query],
                    context=dagent.ContextPolicy(compaction_strategy="cache_aware", compaction_retain_ratio=.0001)), input="Inspect.")
            result = caught.value.result
            assert result.checkpoint is not None
            assert result.plan.context_window_tokens == 131072  # Last valid generation configuration.
            assert [item.call_id for item in result.conversation.items if isinstance(item, dagent.ToolResultMessage)] == ["call_1", "call_2"]
            assert result.conversation.compaction_state.failed_records
            assert len(posts) == 3  # Two generations and one paid summary; no oversized generation.


@pytest.mark.asyncio
@pytest.mark.parametrize("protocol",["chat_completions","responses"])
@pytest.mark.parametrize("stream", [False, True])
async def test_long_run_multiple_compactions_and_portable_resources(tmp_path,protocol,stream):
    steps=0
    summaries=0

    @dagent.tool
    def query(index: int) -> str:
        """Return one batch of evidence."""
        return f"step={index}; verified=true; next={index+1}; " + "evidence " * 180

    def respond(request):
        nonlocal steps,summaries
        body=json.loads(request.content)
        text=json.dumps(body,ensure_ascii=False)
        if "Eligible source IDs:" in text or body.get("instructions","").startswith("Produce a task checkpoint") or (
            protocol=="chat_completions" and body.get("messages",[{}])[0].get("content","").startswith("Produce a task checkpoint")):
            summaries+=1
            # Source IDs are carried both in appended instructions and in
            # isolated source labels. Prefer exact archive ids over inventions.
            history=body.get("messages",body.get("input",[]))
            raw="\n".join(str(item.get("content","")) for item in history)
            match=re.search(r"Eligible source IDs: (\[[^\n]+\])",raw)
            ids=json.loads(match.group(1)) if match else re.findall(r"\[Source ([^;]+);",raw)
            content=json.dumps({"requirements":[{"text":"Continue collecting evidence; preserve task progress.","source_ids":[ids[0]]}]})
            return _completion(protocol,body.get("stream",False),usage=_usage(protocol),content=content)
        steps+=1
        return _completion(protocol,body.get("stream",False),usage=_usage(protocol),content="done" if steps>30 else "",
            calls=() if steps>30 else (ToolCall(id=f"call_{steps}",name="tool_query",arguments={"index":steps}),))

    async with _endpoint(protocol=protocol,token_counting="heuristic",context_window_tokens=8192,
                         max_output_tokens=512,responder=respond) as (provider,posts):
        with closing(dagent.Runner(provider=provider,workspace=tmp_path,skill_roots=[])) as runner:
            agent=dagent.ToolAgent(profile="conversation",capabilities=[query],max_steps=40,
                context=dagent.ContextPolicy(compaction_strategy="cache_aware",summary_max_tokens=512))
            if stream:
                events = [event async for event in runner.stream(agent,
                    input="Collect evidence and preserve progress.", workspace_path=tmp_path/"first")]
                result = events[-1].data.result
                # The synthetic Responses stream supplies a terminal snapshot
                # without text deltas; neither protocol leaks summary tokens.
                deltas = "".join(event.data.delta for event in events if event.type == "response.content.delta")
                assert deltas in {"", "done"}
            else:
                result=await runner.run(agent,input="Collect evidence and preserve progress.",workspace_path=tmp_path/"first")
            assert result.status == "completed"
            assert result.output_text == "done"
            assert summaries>=2
            assert all(usage.estimated_input_tokens<=usage.input_budget_tokens for usage in result.state.context_usage)
            assert result.conversation.summary.compaction_record
            continued=await runner.run(agent,input="Continue.",conversation=result.conversation,workspace_path=tmp_path/"second")
            assert continued.status == "completed"
            assert (tmp_path/"second"/result.conversation.summary.compaction_record.path).is_file()
