@pytest.mark.asyncio
async def test_failed_soft_compaction_keeps_source_and_does_not_retry_unchanged_span():
    source = _history("evidence " * 950)
    assembler = ContextAssembler(context_window_tokens=4096,max_output_tokens=512)
    compactor = _Compactor(fail=True)
    policy = dagent.ContextPolicy(compaction_strategy="chunked", compaction_trigger_ratio=.4)
    first = await assembler.prepare(system_message={"content":"instructions"}, conversation=source,
        policy=policy, enable_new_strategy=True, history_compactor=compactor)
    assert first.conversation.items == source.items
    assert len(compactor.calls) == 1
    assert first.conversation.compaction_state.failed_sources
    second = await assembler.prepare(system_message={"content":"instructions"}, conversation=first.conversation,
        policy=policy, enable_new_strategy=True, history_compactor=compactor)
    assert len(compactor.calls) == 1
    assert second.conversation.items == source.items


