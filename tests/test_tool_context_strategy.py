@pytest.mark.asyncio
async def test_runner_overflow_preserves_latest_tool_batch_and_checkpoint(tmp_path):
    @dagent.tool
    def query(value: str) -> str:
        """Return a result."""
        return "complete received result " * 2000

    def respond(request):
        body=json.loads(request.content)
        return _completion("chat_completions",body.get("stream",False),usage=_usage("chat_completions"),content="",
            calls=(ToolCall(id="call",name="tool_query",arguments={"value":"mandatory args " * 3000}),))

    async with _endpoint(protocol="chat_completions",token_counting="heuristic",context_window_tokens=4096,
                         max_output_tokens=512,responder=respond) as (provider,posts):
        with closing(dagent.Runner(provider=provider,workspace=tmp_path,skill_roots=[])) as runner:
            with pytest.raises(dagent.ContextWindowExceeded) as caught:
                await runner.run(dagent.ToolAgent(profile="conversation",capabilities=[query],
                    context=dagent.ContextPolicy(compaction_strategy="cache_aware")), input="Inspect.")
            result=caught.value.result
            assert result.status == "failed"
            assert result.checkpoint is not None
            assert result.error.code == "ContextWindowExceeded"
            assert result.conversation.items[-1].call_id == "call"
            assert "complete received result" in stored_content_text(result.conversation.items[-1].content)
            assert len(posts) == 1


